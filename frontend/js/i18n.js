let currentLocale = 'en';

export function setLocale(locale) {
  if (I18N_STRINGS[locale]) {
    currentLocale = locale;
    document.documentElement.setAttribute('lang', locale);
    localStorage.setItem('aegispath_locale', locale);
  }
}

export function getLocale() {
  return currentLocale;
}

export function t(key) {
  const dict = I18N_STRINGS[currentLocale] || I18N_STRINGS.en;
  return dict[key] || I18N_STRINGS.en[key] || key;
}

// Bilingual label renderer
export function b(primaryKey, subKey) {
  const primaryText = t(primaryKey);
  const subText = subKey ? t(subKey) : "";
  if (!subText) return primaryText;

  return `<span class="label-primary">${primaryText}</span> <span class="label-sub">${subText}</span>`;
}
