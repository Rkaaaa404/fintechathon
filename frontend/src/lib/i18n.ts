export function t(key: string, locale: Locale = 'en'): string {
  return I18N_STRINGS[locale]?.[key] || I18N_STRINGS['en']?.[key] || key;
}

export function b(enKey: string, zhKey: string, locale: Locale = 'en'): React.ReactNode {
  const dict = I18N_STRINGS[locale] || I18N_STRINGS.en;
  const primaryText = dict[enKey] || enKey;
  const subText = dict[zhKey] || '';

  const showSub = Boolean(subText && subText.trim() !== primaryText.trim());

  return React.createElement(
    React.Fragment,
    null,
    React.createElement('span', { className: 'label-primary' }, primaryText),
    showSub ? ' ' : null,
    showSub ? React.createElement('span', { className: 'label-sub' }, subText) : null
  );
}

